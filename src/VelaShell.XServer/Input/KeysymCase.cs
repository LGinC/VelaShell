    private static readonly Dictionary<int, uint> LegacyByCodePoint = BuildReverse();

    private static Dictionary<int, uint> BuildReverse()
    {
        Dictionary<int, uint> map = new(Legacy.Length);
        foreach ((ushort keysym, ushort codePoint) in Legacy)
        {
            map[codePoint] = keysym;
        }
        return map;
    }

    /// <summary>键值对应的 Unicode 码位(只管 Latin-1、附录 A 表里的字母与基本平面的 Unicode 键值);别的返回 −1。</summary>
    public static int ToCodePoint(uint keysym)
    {
        if (keysym is >= 0x20 and <= 0xFF)
        {
            return (int)keysym;
        }
        if (keysym is >= UnicodeBase + 0x100 and <= UnicodeBase + 0xFFFF)
        {
            return (int)(keysym - UnicodeBase);
        }
        if (keysym > 0xFFFF)
        {
            return -1;
        }
        int lo = 0, hi = Legacy.Length - 1;
        while (lo <= hi)
        {
            int mid = (lo + hi) / 2;
            if (Legacy[mid].Keysym == keysym)
            {
                return Legacy[mid].CodePoint;
            }
            if (Legacy[mid].Keysym < keysym)
            {
                lo = mid + 1;
            }
            else
            {
                hi = mid - 1;
            }
        }
        return -1;
    }

    /// <summary>码位 → 键值:Latin-1 用自己;<paramref name="legacy" /> 时附录 A 表里有的用传统键值,其余用 Unicode 键值。</summary>
    private static uint FromCodePoint(int codePoint, bool legacy) =>
        codePoint <= 0xFF ? (uint)codePoint
        : legacy && LegacyByCodePoint.TryGetValue(codePoint, out uint keysym) ? keysym
        : UnicodeBase + (uint)codePoint;

    /// <summary>
    /// 有大小写之分的字母给出 (小写, 大写) 两个键值(与给的键值同一种编码:传统键值给传统的,Unicode 键值给 Unicode 的),否则 null。
    /// </summary>
    public static (uint Lower, uint Upper)? CasePair(uint keysym)
    {
        int cp = ToCodePoint(keysym);
        if (cp < 0)
        {
            return null;
        }
        char c = (char)cp;
        int lower = char.ToLowerInvariant(c), upper = char.ToUpperInvariant(c);
        if (lower == upper)
        {
            return null;
        }
        bool legacy = keysym < UnicodeBase;
        return (FromCodePoint(lower, legacy), FromCodePoint(upper, legacy));
    }

    /// <summary><paramref name="lower" /> 是小写字母、<paramref name="upper" /> 是它的大写(两边的编码可以不同:码位对得上就算)。</summary>
    public static bool IsCasePair(uint lower, uint upper)
    {
        int l = ToCodePoint(lower), u = ToCodePoint(upper);
        return l >= 0 && u >= 0 && l != u && char.ToUpperInvariant((char)l) == u && char.ToLowerInvariant((char)l) == l;
    }
